import React, { useMemo } from 'react';
import {
  LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip, Legend, ResponsiveContainer
} from 'recharts';

const RotationCurves = ({ parameters }) => {
  const { mass, rho0, Re } = parameters;

  const data = useMemo(() => {
    const points = [];

    // Generate data points for radius from 0.1 to 20
    for (let r = 0.5; r <= 20; r += 0.5) {
      // 1. Newtonian Prediction (Keplerian decline): v ~ sqrt(GM/r)
      const vNewtonian = Math.sqrt(mass * 10 / r);

      // 2. GTH Prediction (includes Inverse Energy Cascade wake term)
      // v ~ sqrt(GM/r + beta * r)
      // Beta (wake strength) depends on Reynolds number and substrate density
      const beta = (Re / 1000) * (rho0 / 10) * 0.5;
      const vGTH = Math.sqrt(mass * 10 / r + beta * r);

      points.push({
        radius: r,
        newtonian: parseFloat(vNewtonian.toFixed(2)),
        gth: parseFloat(vGTH.toFixed(2)),
      });
    }

    return points;
  }, [mass, rho0, Re]);

  return (
    <div className="w-full h-full relative flex flex-col items-center justify-center p-8">
      <div className="absolute top-4 left-4 z-10 bg-slate-900/80 p-4 rounded border border-slate-700 max-w-md pointer-events-none">
        <h3 className="text-xl font-bold text-blue-400 mb-2">Galactic Rotation Curves</h3>
        <p className="text-sm text-slate-300 mb-2">
          Comparing the standard Newtonian prediction (which falls off with distance) against the
          GTH framework prediction. The GTH flat curve emerges from the macroscopic fluid wake
          generated by the inverse energy cascade, not from Dark Matter.
        </p>
        <ul className="text-xs text-slate-400 mt-2 list-disc list-inside">
          <li><strong>M (Central Mass)</strong>: Affects the initial peak velocity.</li>
          <li><strong>Re (Reynolds Number)</strong>: Affects the strength of the inverse cascade (flatness).</li>
          <li><strong>ρ_0 (Fluid Density)</strong>: Scales the wake coupling strength.</li>
        </ul>
      </div>

      <div className="w-full max-w-4xl h-[600px] bg-slate-900/50 p-6 rounded-xl border border-slate-700 shadow-2xl mt-16 flex flex-col items-center justify-center">
        <h2 className="text-2xl font-bold text-center mb-6 text-slate-200">Orbital Velocity vs Radius</h2>

        <ResponsiveContainer width="100%" height="90%">
          <LineChart
            data={data}
            margin={{ top: 20, right: 30, left: 20, bottom: 20 }}
          >
            <CartesianGrid strokeDasharray="3 3" stroke="#334155" />
            <XAxis
              dataKey="radius"
              stroke="#94a3b8"
              label={{ value: 'Radius (kpc)', position: 'bottom', fill: '#94a3b8' }}
            />
            <YAxis
              stroke="#94a3b8"
              label={{ value: 'Velocity (km/s)', angle: -90, position: 'left', fill: '#94a3b8' }}
              domain={[0, 'auto']}
            />
            <Tooltip
              contentStyle={{ backgroundColor: '#0f172a', borderColor: '#334155', color: '#f8fafc' }}
              itemStyle={{ color: '#f8fafc' }}
            />
            <Legend verticalAlign="top" height={36} />

            <Line
              type="monotone"
              dataKey="newtonian"
              name="Newtonian (Expected)"
              stroke="#f43f5e"
              strokeWidth={3}
              strokeDasharray="5 5"
              dot={false}
            />
            <Line
              type="monotone"
              dataKey="gth"
              name="GTH Wake (Predicted)"
              stroke="#3b82f6"
              strokeWidth={4}
              dot={false}
              activeDot={{ r: 8 }}
            />
          </LineChart>
        </ResponsiveContainer>
      </div>
    </div>
  );
};

export default RotationCurves;
